pub fn lanczos_sum(x: f64) -> f64 {
    rational_function(x, &LANCZOS_NUM, &LANCZOS_DENOM)
}

pub fn lanczos_sum_near_1(dx: f64) -> f64 {
    let mut result = 0.0;
    for k in 1..=12 {
        let k_f = k as f64;
        result += (-LANCZOS_SUM_NEAR_1_D[k - 1] * dx) / (k_f * dx + k_f * k_f);
    }
    result
}

pub fn lanczos_sum_near_2(dx: f64) -> f64 {
    let mut result = 0.0;
    let x = dx + 2.0;
    for k in 1..=12 {
        let k_f = k as f64;
        result += (-LANCZOS_SUM_NEAR_2_D[k - 1] * dx)
            / (x + k_f * x + k_f * k_f - 1.0);
    }
    result
}

